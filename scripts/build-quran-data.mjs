/**
 * Builds the offline Quran dataset bundled with the app.
 *
 * Sources (quran.com API v4):
 *  - Chapter metadata (FR + EN)
 *  - Uthmani text (all 6236 verses)
 *  - Translations: FR Muhammad Hamidullah (31), EN Saheeh International (20)
 *  - Transliteration (57)
 *
 * Output:
 *  - src/data/quran/chapters.json
 *  - src/data/quran/verses/surah-<n>.json  (one file per surah, lazy-loaded)
 *
 * Usage: node scripts/build-quran-data.mjs
 */
import { mkdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const API = "https://api.quran.com/api/v4";
const FR_TRANSLATION_ID = 31; // Muhammad Hamidullah
const EN_TRANSLATION_ID = 20; // Saheeh International
const TRANSLITERATION_ID = 57;

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const outDir = path.join(root, "src", "data", "quran");

async function getJson(url) {
  const res = await fetch(url);
  if (!res.ok) throw new Error(`${res.status} ${res.statusText} for ${url}`);
  return res.json();
}

/** Strips HTML tags and footnote markers that Saheeh International embeds. */
function cleanText(text) {
  return text
    .replace(/<sup[^>]*>.*?<\/sup>/g, "")
    .replace(/<[^>]+>/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

async function fetchChapters() {
  const [fr, en] = await Promise.all([
    getJson(`${API}/chapters?language=fr`),
    getJson(`${API}/chapters?language=en`),
  ]);
  return fr.chapters.map((c, i) => ({
    id: c.id,
    nameArabic: c.name_arabic,
    nameSimple: c.name_simple,
    nameFr: c.translated_name.name,
    nameEn: en.chapters[i].translated_name.name,
    revelationPlace: c.revelation_place,
    versesCount: c.verses_count,
  }));
}

async function fetchAllTranslations(id) {
  const data = await getJson(`${API}/quran/translations/${id}`);
  return data.translations.map((t) => cleanText(t.text));
}

async function main() {
  console.log("Fetching chapters…");
  const chapters = await fetchChapters();

  console.log("Fetching Uthmani text + translations…");
  const [uthmani, fr, en, translit] = await Promise.all([
    getJson(`${API}/quran/verses/uthmani`),
    fetchAllTranslations(FR_TRANSLATION_ID),
    fetchAllTranslations(EN_TRANSLATION_ID),
    fetchAllTranslations(TRANSLITERATION_ID),
  ]);

  const verses = uthmani.verses;
  if (
    verses.length !== 6236 ||
    fr.length !== verses.length ||
    en.length !== verses.length ||
    translit.length !== verses.length
  ) {
    throw new Error(
      `Inconsistent verse counts: uthmani=${verses.length} fr=${fr.length} en=${en.length} translit=${translit.length}`
    );
  }

  // Group verses per surah, keyed by verse_key "S:V" to guarantee alignment.
  const bySurah = new Map();
  verses.forEach((verse, i) => {
    const [surah, ayah] = verse.verse_key.split(":").map(Number);
    if (!bySurah.has(surah)) bySurah.set(surah, []);
    bySurah.get(surah).push({
      v: ayah,
      ar: verse.text_uthmani,
      fr: fr[i],
      en: en[i],
      tr: translit[i],
    });
  });

  await mkdir(path.join(outDir, "verses"), { recursive: true });
  await writeFile(
    path.join(outDir, "chapters.json"),
    JSON.stringify(chapters, null, 1)
  );

  for (const [surah, list] of bySurah) {
    const expected = chapters[surah - 1].versesCount;
    if (list.length !== expected) {
      throw new Error(`Surah ${surah}: got ${list.length} verses, expected ${expected}`);
    }
    await writeFile(
      path.join(outDir, "verses", `surah-${surah}.json`),
      JSON.stringify(list)
    );
  }

  // Static require map so Metro can bundle every surah file.
  const indexLines = [
    "// Generated by scripts/build-quran-data.mjs, do not edit.",
    "export const verseFiles: Record<number, () => unknown> = {",
    ...Array.from({ length: 114 }, (_, i) => `  ${i + 1}: () => require("./surah-${i + 1}.json"),`),
    "};",
    "",
  ];
  await writeFile(path.join(outDir, "verses", "index.ts"), indexLines.join("\n"));

  console.log(`Done: ${chapters.length} chapters, ${verses.length} verses written to src/data/quran/`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
